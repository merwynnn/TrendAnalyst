#!/usr/bin/env bash
# Trend Analyst — the gate.
#
# Runs every check the build brief requires and prints markdown with RAW output, so
# evidence is generated rather than remembered:
#
#     bash scripts/gate.sh > docs/evidence/P0-gate.md
#
# Checks that cannot pass yet because their phase has not landed are reported as
# PENDING with the reason, and do not fail the gate. That is deliberate: a gate that
# has to be edited to stay honest stops being evidence.
#
# Exit code: 0 when every runnable check passes, 1 otherwise.
set -uo pipefail

cd "$(dirname "$0")/.." || exit 2
export UV_PYTHON_DOWNLOADS=never UV_NO_MANAGED_PYTHON=1

failures=0
pendings=0

header() {
  printf '\n### %s\n\n' "$1"
}

check() { # check <title> <command...>
  local title="$1"
  shift
  header "$title"
  printf '```console\n$ %s\n' "$*"
  local out
  if out="$("$@" 2>&1)"; then
    printf '%s\n```\n\n**RESULT: PASS**\n' "$out"
  else
    printf '%s\n```\n\n**RESULT: FAIL (exit %s)**\n' "$out" "$?"
    failures=$((failures + 1))
  fi
}

pending() { # pending <title> <reason> <command...>
  local title="$1" reason="$2"
  shift 2
  pendings=$((pendings + 1))
  header "$title"
  printf '```console\n$ %s\n' "$*"
  printf '%s\n```\n\n**RESULT: PENDING — %s**\n' "$("$@" 2>&1)" "$reason"
}

# --- environment -------------------------------------------------------------
printf '# Trend Analyst — evidence log\n\n'
printf 'Generated by `scripts/gate.sh` on %s.\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
printf '\nInterpreter: `%s`\n' "$(uv run python -c 'import sys; print(sys.version.split()[0] + " (" + sys.executable + ")")' 2>/dev/null)"

# --- always runnable ---------------------------------------------------------
check "pytest — no database, no network" uv run pytest -q -m "not db"
check "ruff — lint clean" uv run ruff check .
check "mypy — strict, python_version=3.12" uv run mypy src config

# --- configuration ------------------------------------------------------------
config_cli_probe() {
  uv run python - <<'PY'
import json
import subprocess
import sys

out = subprocess.run(
    [sys.executable, "-m", "config.cli", "show", "--json"],
    capture_output=True,
    text=True,
    check=True,
)
data = json.loads(out.stdout)
layers = ", ".join(
    f"{layer['label']}={'loaded' if layer['exists'] else 'absent'}" for layer in data["layers"]
)
redacted = data["settings"]["db"]["url"] in ("", "***")
print(f"layers (high->low): {layers}")
print(f"credentials configured: {sum(1 for ok in data['credentials_configured'].values() if ok)}")
print(f"db.url redacted: {redacted}")
assert redacted, "the config CLI leaked a secret"
PY
}
check "config CLI — every layer resolved, secrets redacted" config_cli_probe

# --- registry ------------------------------------------------------------------
registry_probe() {
  uv run python - <<'PY'
import subprocess
import sys

out = subprocess.run(
    [sys.executable, "-m", "config.cli", "registry", "--json"],
    capture_output=True,
    text=True,
    check=True,
)
import json

data = json.loads(out.stdout)
summary = data["summary"]
print(
    f"{summary['total']} sources ({summary['tier_s']} Tier S, {summary['tier_a']} Tier A) · "
    f"{summary['enabled']} enabled, {summary['disabled']} disabled"
)
print(f"L0 collect: {summary['l0']} · L2 enrich: {summary['l2']}")
print(f"execution order starts: {', '.join(s['id'] for s in data['sources'][:3])} ...")
print(f"egress allowlist entries: {sum(len(v) for v in data['allowed_domains'].values())}")

l0 = [s for s in data["sources"] if "L0" in s["layers"]]
assert all(s["tier"] == "S" for s in l0), "Tier A slipped into L0"
assert all(s["enabled"] for s in l0), "an L0 source is disabled"
assert all(not s["enabled"] for s in data["sources"] if s["tier"] == "A"), (
    "a Tier-A source is enabled without its credential being verified"
)
PY
}
check "source registry — catalog, execution order, Tier-A never in L0" registry_probe

# --- L0 collection, replayed from the recorded fixtures (P1) ------------------
l0_replay_probe() {
  uv run python - <<'PY'
import json
import subprocess
import sys

SOURCES = ["--source", "hn_firebase", "--source", "wiki_pageviews", "--source", "arctic_shift"]

def run() -> dict:
    out = subprocess.run(
        [sys.executable, "-m", "trend_analyst.pipeline.orchestrator",
         "--fixtures", "tests/data", "--json", *SOURCES],
        capture_output=True, text=True, check=True,
    )
    return json.loads(out.stdout)

first = run()
second = run()
print(f"run 1: status={first['status']} signals={first['items_new']} "
      f"requests={first['quota_spent']}")
print(f"run 2: status={second['status']} signals={second['items_new']} "
      f"requests={second['quota_spent']}")
for outcome in second["outcomes"]:
    print(f"  {outcome['source_id']:<20} {outcome['status']:<8} "
          f"new={outcome['items_new']:<4} parsed={outcome['signals_parsed']:<4} "
          f"requests={outcome['quota_spent']}")
assert second["items_new"] == 0, "a repeated L0 run must store no new signals"
assert all(o["signals_parsed"] == 0 for o in second["outcomes"]), (
    "a repeated L0 run must not re-parse identical payloads"
)
PY
}
check "L0 replay — repeated run stores and parses nothing new" l0_replay_probe

# --- registry → database sync (P0-T6) -----------------------------------------
if uv run python -c "
import socket, sys
s = socket.socket(); s.settimeout(2)
sys.exit(0 if s.connect_ex(('127.0.0.1', 5432)) == 0 else 1)
" 2>/dev/null; then
  check "registry sync — second run is a no-op" uv run python -m scripts.sync_sources
  check "registry sync — idempotent (dry run reports zero changes)" \
    uv run python -m scripts.sync_sources --dry-run
else
  pending "registry sync" "no Postgres reachable on 127.0.0.1:5432" \
    uv run python -m scripts.sync_sources
fi

# --- needs Postgres ----------------------------------------------------------
if uv run python -c "
import socket, sys
s = socket.socket(); s.settimeout(2)
sys.exit(0 if s.connect_ex(('127.0.0.1', 5432)) == 0 else 1)
" 2>/dev/null; then
  check "pytest — full suite against local Postgres + pgvector" uv run pytest -q
  if [ -f alembic.ini ] && compgen -G "migrations/versions/*.py" >/dev/null; then
    check "alembic — upgrade head" uv run alembic upgrade head
    check "alembic — zero drift between models and migrations" uv run alembic check
  else
    pending "alembic — upgrade head" "migrations land in bean P0-T5" uv run alembic upgrade head
  fi
else
  pending "pytest — full suite" "no Postgres reachable on 127.0.0.1:5432 (run: wsl -d Ubuntu -u root -- bash scripts/provision_pg.sh)" uv run pytest -q
fi

# --- health (P0-T7) ------------------------------------------------------------
# The CLI's contract is checked here; the *state* it reports (empty-but-healthy) is
# asserted in the test suite against the isolated database, because the development
# database legitimately accumulates real runs.
health_probe() {
  uv run python - <<'PY'
import json
import subprocess
import sys

out = subprocess.run(
    [sys.executable, "-m", "trend_analyst.health", "--json"],
    capture_output=True,
    text=True,
    check=False,
)
payload = json.loads(out.stdout)
status = payload["status"]
expected = {"healthy": 0, "degraded": 1, "down": 2}[status]
print(f"status: {status} (exit {out.returncode}, expected {expected})")
print(f"database: {'ok' if payload['database']['ok'] else 'DOWN'}")
print(f"sources: {len(payload['sources'])} · reasons: {payload.get('reasons')}")
assert out.returncode == expected, f"exit code must match the status ({status})"
assert payload["database"]["ok"], "the database must be reachable for this check"
PY
}
check "health CLI — valid report, exit code matches status" health_probe
# --- summary -----------------------------------------------------------------
header "Summary"
if [ "$failures" -eq 0 ]; then
  printf 'GATE: PASS (%s pending)\n' "$pendings"
  exit 0
fi
printf 'GATE: FAIL — %s check(s) failed\n' "$failures"
exit 1
