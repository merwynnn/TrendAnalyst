#!/usr/bin/env bash
# Trend Analyst — the gate.
#
# Runs every check the build brief requires and prints markdown with RAW output, so
# evidence is generated rather than remembered:
#
#     bash scripts/gate.sh > docs/evidence/P0-gate.md
#
# Checks that cannot pass yet because their phase has not landed are reported as
# PENDING with the reason, and do not fail the gate. That is deliberate: a gate that
# has to be edited to stay honest stops being evidence.
#
# Exit code: 0 when every runnable check passes, 1 otherwise.
set -uo pipefail

cd "$(dirname "$0")/.." || exit 2
export UV_PYTHON_DOWNLOADS=never UV_NO_MANAGED_PYTHON=1

failures=0
pendings=0

header() {
  printf '\n### %s\n\n' "$1"
}

check() { # check <title> <command...>
  local title="$1"
  shift
  header "$title"
  printf '```console\n$ %s\n' "$*"
  local out
  if out="$("$@" 2>&1)"; then
    printf '%s\n```\n\n**RESULT: PASS**\n' "$out"
  else
    printf '%s\n```\n\n**RESULT: FAIL (exit %s)**\n' "$out" "$?"
    failures=$((failures + 1))
  fi
}

pending() { # pending <title> <reason> <command...>
  local title="$1" reason="$2"
  shift 2
  pendings=$((pendings + 1))
  header "$title"
  printf '```console\n$ %s\n' "$*"
  printf '%s\n```\n\n**RESULT: PENDING — %s**\n' "$("$@" 2>&1)" "$reason"
}

# --- environment -------------------------------------------------------------
printf '# Trend Analyst — evidence log\n\n'
printf 'Generated by `scripts/gate.sh` on %s.\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
printf '\nInterpreter: `%s`\n' "$(uv run python -c 'import sys; print(sys.version.split()[0] + " (" + sys.executable + ")")' 2>/dev/null)"

# --- always runnable ---------------------------------------------------------
check "pytest — no database, no network" uv run pytest -q -m "not db"
check "ruff — lint clean" uv run ruff check .
check "mypy — strict, python_version=3.12" uv run mypy src config

# --- configuration ------------------------------------------------------------
config_cli_probe() {
  uv run python - <<'PY'
import json
import subprocess
import sys

out = subprocess.run(
    [sys.executable, "-m", "config.cli", "show", "--json"],
    capture_output=True,
    text=True,
    check=True,
)
data = json.loads(out.stdout)
layers = ", ".join(
    f"{layer['label']}={'loaded' if layer['exists'] else 'absent'}" for layer in data["layers"]
)
redacted = data["settings"]["db"]["url"] in ("", "***")
print(f"layers (high->low): {layers}")
print(f"credentials configured: {sum(1 for ok in data['credentials_configured'].values() if ok)}")
print(f"db.url redacted: {redacted}")
assert redacted, "the config CLI leaked a secret"
PY
}
check "config CLI — every layer resolved, secrets redacted" config_cli_probe

